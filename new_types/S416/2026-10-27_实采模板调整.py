def pay01(s):
    head, _, body = s.partition('\n## \n')
    old_pre = re.search(r'<仅当 付款方案=[^>]*> - \{\{预付款比例\}\}%预付款：[^\n]*', body).group(0)
    docs = re.search(r'\n  卖方需提供正确的100%增值税发票原件[^\n]*', body).group(0)
    adj = re.search(r'<仅当 付款方案=[^>]*> - \{\{调试款比例\}\}%调试款：[^\n]*', body).group(0)
    basis = re.search(r'设备（或货物）内在质量验收合格[^\n]*', body).group(0)
    new = [
        '<不出现于 付款方案=%s>%s' % (D, old_pre),
        '- {{到货款比例}}%到货款：卖方应根据买方下发的订单提供货物，买方在收到标的物验收合格，且收到卖方以下文件后，在（{{付款天数}}）日历日内，向卖方支付该批订单合同标的物价格的（{{到货款比例}}%）：',
        docs.lstrip('\n'),
        '<不出现于 付款方案=%s>%s' % (D, adj),
        '<仅当 付款方案=%s> - {{质保比例}}%%质保金：' % D,
        '<仅当 付款方案=%s>   质保金为每批订单总价的（{{质保比例}}）%%。标的物质保期满且无质量或遗留问题，卖方向买方提交释放保证金申请函，买方确认并无异议后（{{质保金_释放天数}}）个日历日内向卖方无息付清质量保证金。' % D,
        '<仅当 付款方案=%s|%s>   %s' % (A, D, basis),
    ]
    return head + '\n## \n\n' + '\n\n'.join(new) + '\n'


